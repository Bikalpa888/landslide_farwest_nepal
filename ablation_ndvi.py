"""
Ablation test: how much of the performance comes from NDVI (and land cover)?

Runs XGBoost and LR with
  A) all factors (as in the paper)
  B) without NDVI
  C) without NDVI and without land cover
under the same repeated random and 5 km spatial cross-validation, plus the
temporal test (1992-2010 -> 2011-2018). Uses the same seeds as the paper.

Usage:  python ablation_ndvi.py      (about 10 minutes on Colab)
Output: results/ablation_ndvi.md, results/tables/ablation_ndvi_folds.csv
"""
import importlib
import json

import numpy as np
import pandas as pd

import config as C

exp = importlib.import_module("03_experiments")

MODELS = ["LR", "XGBoost"]


def run():
    names = json.loads((C.PROC / "feature_names.json").read_text())
    df = pd.read_csv(C.PROC / "samples.csv")
    y = df.label.values
    variants = {
        "A. All factors": names,
        "B. Without NDVI": [n for n in names if n != "ndvi"],
        "C. Without NDVI and land cover": [n for n in names if n not in ("ndvi", "landcover")],
    }

    rows = []
    for vname, vnames in variants.items():
        X = exp.design_matrix(df, vnames).values
        for rep in range(C.N_REPEATS):
            seed = C.SEED + rep
            schemes = {"Random": exp.random_folds(y, seed),
                       "Spatial": exp.block_folds(df.x.values, df.y.values, C.BLOCK_SIZE_M, seed)[0]}
            for scheme, folds in schemes.items():
                for m in MODELS:
                    for r in exp.run_cv(X, y, folds, m):
                        rows.append({"variant": vname, "scheme": scheme, "model": m, "repeat": rep, **r})
        print("done:", vname)
    res = pd.DataFrame(rows)
    res.to_csv(C.TABLES / "ablation_ndvi_folds.csv", index=False)

    lines = ["# NDVI ablation (generated by ablation_ndvi.py)", "",
             "## Cross-validation AUC (mean ± SD over 25 folds)", "",
             "| Factors | Model | AUC random | AUC spatial | Gap |", "|---|---|---|---|---|"]
    g = res.groupby(["variant", "model", "scheme"]).AUC.agg(["mean", "std"])
    for v in variants:
        for m in MODELS:
            a, b = g.loc[(v, m, "Random")], g.loc[(v, m, "Spatial")]
            lines.append(f"| {v} | {m} | {a['mean']:.3f} ± {a['std']:.3f} | {b['mean']:.3f} ± {b['std']:.3f} | "
                         f"{a['mean'] - b['mean']:.3f} |")

    # temporal test for each variant (same construction as 03_experiments.py)
    d = pd.read_csv(C.PROC / "dated_samples.csv")
    neg = df[df.label == 0].sample(frac=1, random_state=C.SEED)
    old, new = d[d.year <= C.TEMPORAL_SPLIT_YEAR], d[d.year > C.TEMPORAL_SPLIT_YEAR]
    n_tr = min(len(old), int(len(neg) * len(old) / (len(old) + len(new))))
    train = pd.concat([old.assign(label=1), neg.iloc[:n_tr]])
    test = pd.concat([new.assign(label=1), neg.iloc[n_tr:n_tr + len(new)]])
    lines += ["", f"## Temporal transfer AUC (train ≤ {C.TEMPORAL_SPLIT_YEAR}, test after)", "",
              "| Factors | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for v, vnames in variants.items():
        cols = exp.design_matrix(pd.concat([train, test]), vnames).columns
        Xtr = exp.design_matrix(train, vnames).reindex(columns=cols, fill_value=0).values
        Xte = exp.design_matrix(test, vnames).reindex(columns=cols, fill_value=0).values
        vals = []
        for m in MODELS:
            mod = exp.make_models()[m].fit(Xtr, train.label.values)
            vals.append(f"{exp.metrics(test.label.values, mod.predict_proba(Xte)[:, 1])['AUC']:.3f}")
        lines.append(f"| {v} | " + " | ".join(vals) + " |")

    # SHAP ranking without NDVI
    import shap
    vnames = variants["B. Without NDVI"]
    X = exp.design_matrix(df, vnames)
    model = exp.make_models()["XGBoost"].fit(X.values, y)
    idx = np.random.default_rng(C.SEED).choice(len(X), min(C.SHAP_SAMPLE, len(X)), replace=False)
    sv = shap.TreeExplainer(model).shap_values(X.iloc[idx].values)
    imp = pd.Series(np.abs(sv).mean(0), index=[exp.NICE.get(c, c.replace("lc_", "LC: ")) for c in X.columns])
    imp = imp.sort_values(ascending=False).head(10)
    lines += ["", "## Top 10 factors without NDVI (XGBoost, mean |SHAP|)", "", "| Rank | Factor | Mean |SHAP| |", "|---|---|---|"]
    lines += [f"| {i} | {f} | {v:.3f} |" for i, (f, v) in enumerate(imp.items(), 1)]

    out = "\n".join(lines)
    (C.RESULTS / "ablation_ndvi.md").write_text(out, encoding="utf-8")
    print("\n" + out)


if __name__ == "__main__":
    run()
